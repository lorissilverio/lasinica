// FUNZIONE PER CARICARE LE FAQ
// ============================================
function loadFAQs(lang) {
    const container = document.getElementById('faqContainer');
    if (!container) return;
    
    const faqs = faqData[lang] || faqData.it;
    container.innerHTML = '';
    
    faqs.forEach((faq, index) => {
        const faqItem = document.createElement('div');
        faqItem.className = 'faq-item';
        faqItem.innerHTML = `
            <div class="faq-question" data-idx="${index}">
                ❓ ${faq.q} <span class="faq-icon">▼</span>
            </div>
            <div class="faq-answer">${faq.a}</div>
        `;
        container.appendChild(faqItem);
    });
    
    // Aggiungi event listener per le nuove domande
    document.querySelectorAll('.faq-question').forEach(q => {
        q.addEventListener('click', function() {
            const answer = this.nextElementSibling;
            const icon = this.querySelector('.faq-icon');
            answer.classList.toggle('show');
            if (icon) {
                icon.style.transform = answer.classList.contains('show') ? 'rotate(180deg)' : 'rotate(0)';
            }
        });
    });
}

