// SLIDER PER HOME PAGE
// ============================================
function initSlider() {
    const slides = document.querySelectorAll('.slide');
    const dots = document.querySelectorAll('.dot');
    const prevBtn = document.getElementById('sliderPrev');
    const nextBtn = document.getElementById('sliderNext');
    
    if (!slides.length) return;
    
    let slideIndex = 0;
    let slideInterval;
    
    function showSlide(n) {
        slides.forEach(slide => slide.classList.remove('active'));
        dots.forEach(dot => dot.classList.remove('active'));
        if (n >= slides.length) slideIndex = 0;
        if (n < 0) slideIndex = slides.length - 1;
        slides[slideIndex].classList.add('active');
        if (dots[slideIndex]) dots[slideIndex].classList.add('active');
    }
    
    function nextSlide() { slideIndex++; showSlide(slideIndex); resetInterval(); }
    function prevSlide() { slideIndex--; showSlide(slideIndex); resetInterval(); }
    function resetInterval() { clearInterval(slideInterval); slideInterval = setInterval(() => { slideIndex++; showSlide(slideIndex); }, 5000); }
    
    if (prevBtn) prevBtn.addEventListener('click', prevSlide);
    if (nextBtn) nextBtn.addEventListener('click', nextSlide);
    
    dots.forEach((dot, index) => {
        dot.addEventListener('click', () => {
            slideIndex = index;
            showSlide(slideIndex);
            resetInterval();
        });
    });

    // Touch swipe support
    const sliderEl = document.querySelector('.hero-slider');
    if (sliderEl) {
        let touchStartX = 0;
        let touchEndX = 0;
        sliderEl.addEventListener('touchstart', e => {
            touchStartX = e.changedTouches[0].screenX;
        }, { passive: true });
        sliderEl.addEventListener('touchend', e => {
            touchEndX = e.changedTouches[0].screenX;
            const diff = touchStartX - touchEndX;
            if (Math.abs(diff) > 40) {
                if (diff > 0) nextSlide();
                else prevSlide();
            }
        }, { passive: true });
    }
    
    showSlide(0);
    slideInterval = setInterval(() => { slideIndex++; showSlide(slideIndex); }, 5000);
}

